//! Linux desktop integration: the `.desktop` file and the icon theme entry, written by the app.
//!
//! Why this exists at all is [`crate::app_icon`]: on X11 the window icon travels with the window
//! (`_NET_WM_ICON`), so a bare binary already shows the right picture. On Wayland there is no such
//! request — `xdg-toplevel-icon` is not implemented by the shells that matter — so GNOME and KDE
//! resolve the icon (and the display name, and the "open with" registration) by looking the window's
//! `app_id` up in a `.desktop` file and then looking up that file's `Icon=` in an icon theme. Two
//! files, both user-scoped:
//!
//! ```text
//! $XDG_DATA_HOME/applications/<app-id>.desktop              ← matched against the app_id
//! $XDG_DATA_HOME/icons/hicolor/<side>x<side>/apps/zenman.png  ← matched against Icon=
//! ```
//!
//! `--install-desktop-entry` writes them, prints what it wrote, and exits; nothing else ever touches
//! them and running the app stays possible without them. They are also exactly what a packager
//! installs into `/usr/share`, so the same two paths describe the packaged case.
//!
//! A file this module did not generate is never overwritten: [`OWNED_BY`] is the ownership marker,
//! and a foreign file — a distro's entry, or one the user hand-wrote — is reported and left alone.
//! The hicolor PNGs carry no such marker (they are the icon, not a configuration), so they are
//! rewritten whenever they differ.

use std::fmt::{self, Write as _};
use std::path::{Path, PathBuf};

use crate::app_icon::{HICOLOR, HICOLOR_FILE};

/// Marks the files this module owns. A `.desktop` file without it is somebody else's work.
const OWNED_BY: &str =
    "# Generated by `zenman --install-desktop-entry`; delete it to take ownership.";

/// The file name `Icon=` refers to (extension dropped, per the icon-theme spec).
const ICON_NAME: &str = "zenman";

/// What `--install-desktop-entry` did.
#[derive(Debug)]
pub struct Report {
    /// The desktop entry, wherever it landed.
    pub desktop_file: PathBuf,
    /// The hicolor icon files, one per size directory.
    pub icons: Vec<PathBuf>,
    /// Files whose bytes changed (created or rewritten).
    pub written: usize,
    /// Human-readable notes: what was left alone, and why.
    pub notes: Vec<String>,
}

impl fmt::Display for Report {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(f, "desktop entry: {}", self.desktop_file.display())?;
        for icon in &self.icons {
            writeln!(f, "theme icon:    {}", icon.display())?;
        }
        write!(f, "{} file(s) written", self.written)?;
        for note in &self.notes {
            write!(f, "\nnote: {note}")?;
        }
        Ok(())
    }
}

/// Why integration could not be written.
#[derive(Debug)]
pub struct InstallError(pub String);

impl fmt::Display for InstallError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

/// Write the desktop entry and the icon-theme files for a running binary.
///
/// `app_id` is the Wayland `app_id` and the desktop-file basename the window is created with, and
/// `title` the name shown in the panel; both come from `main`, so the entry cannot drift from the
/// window. `home` is the fallback base for `XDG_DATA_HOME` (plan §5.1's two-step resolution).
pub fn install(app_id: &str, title: &str, home: Option<&Path>) -> Result<Report, InstallError> {
    let base = data_home(home)?;
    let exe = std::env::current_exe()
        .map_err(|e| InstallError(format!("cannot work out which binary is running: {e}")))?;

    let mut report = Report {
        desktop_file: base.join("applications").join(format!("{app_id}.desktop")),
        icons: Vec::new(),
        written: 0,
        notes: Vec::new(),
    };

    match write_owned(&report.desktop_file, render(app_id, title, &exe).as_bytes())? {
        Written::Created | Written::Updated => report.written += 1,
        Written::Unchanged => report.notes.push(format!(
            "{} was already current",
            report.desktop_file.display()
        )),
        Written::Foreign => report.notes.push(format!(
            "{} exists and was not written by zenman, so it was left alone: its own `Icon=` and \
             `Exec=` are what the shell will show",
            report.desktop_file.display()
        )),
    }

    for (side, bytes) in HICOLOR {
        let target = base
            .join("icons/hicolor")
            .join(format!("{side}x{side}"))
            .join("apps")
            .join(HICOLOR_FILE);
        if matches!(
            write_exact(&target, bytes)?,
            Written::Created | Written::Updated
        ) {
            report.written += 1;
        }
        report.icons.push(target);
    }

    Ok(report)
}

/// The desktop-entry text for `exe`, in the key order the spec's own examples use.
fn render(app_id: &str, title: &str, exe: &Path) -> String {
    let exec = quote_token(&exe.display().to_string());
    let mut out = String::new();
    let _ = writeln!(out, "{OWNED_BY}");
    let _ = writeln!(out, "[Desktop Entry]");
    let _ = writeln!(out, "Type=Application");
    let _ = writeln!(out, "Version=1.0");
    let _ = writeln!(out, "Name={title}");
    let _ = writeln!(out, "GenericName=File manager");
    let _ = writeln!(
        out,
        "Comment=Dockable multi-pane, multi-tab file manager with archive browsing and undo"
    );
    // `%u` is what a desktop hands a file manager for "open this": a `file:` URI, which `Cli` takes
    // as a positional target (plan §5.9's file-manager contract).
    let _ = writeln!(out, "Exec={exec} %u");
    let _ = writeln!(out, "TryExec={exec}");
    let _ = writeln!(out, "Icon={ICON_NAME}");
    let _ = writeln!(out, "Terminal=false");
    let _ = writeln!(out, "Categories=Utility;Core;FileManager;");
    let _ = writeln!(out, "Keywords=file;manager;folder;archive;tab;pane;undo;");
    // `inode/directory` is the claim that makes zenman a candidate for "set as default file
    // manager", and `x-scheme-handler/file` the one that makes `xdg-open <dir>` land here.
    let _ = writeln!(out, "MimeType=inode/directory;x-scheme-handler/file;");
    // Both halves of the focus story: the launcher passes an activation token, and the forked
    // egui-winit consumes it at window creation (`egui-winit/src/lib.rs`, the activation block).
    let _ = writeln!(out, "StartupNotify=true");
    // The X11 half of the same matching: winit's `with_name(app_id, "")` makes the window answer to
    // `WM_CLASS = ("", app_id)`, so the panel groups a `ZenMan.desktop` tile with the window only if
    // the entry says the class — which is the `app_id`, verified against a live X11 window.
    let _ = writeln!(out, "StartupWMClass={app_id}");
    out
}

/// Quote one `Exec` token the way the desktop-entry spec asks: bare when nothing in it is special,
/// `"`-quoted with `"` and `\` escaped otherwise (a path with a space is the case that matters).
fn quote_token(token: &str) -> String {
    let plain = token
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '.' | '/' | '-' | '+' | '@'));
    if plain {
        return token.to_string();
    }
    let mut out = String::with_capacity(token.len() + 2);
    out.push('"');
    for c in token.chars() {
        if matches!(c, '"' | '\\') {
            out.push('\\');
        }
        out.push(c);
    }
    out.push('"');
    out
}

#[derive(PartialEq, Eq, Debug)]
enum Written {
    Created,
    Updated,
    Unchanged,
    /// A file this module does not own was in the way.
    Foreign,
}

/// Write `bytes` to `path`, unless a file without [`OWNED_BY`] is already there.
fn write_owned(path: &Path, bytes: &[u8]) -> Result<Written, InstallError> {
    let Some(existing) = read_or_nothing(path)? else {
        create_parent(path)?;
        write(path, bytes)?;
        return Ok(Written::Created);
    };
    if !contains_marker(&existing) {
        return Ok(Written::Foreign);
    }
    if existing == bytes {
        return Ok(Written::Unchanged);
    }
    write(path, bytes)?;
    Ok(Written::Updated)
}

/// Write `bytes` unless the file already holds exactly them.
fn write_exact(path: &Path, bytes: &[u8]) -> Result<Written, InstallError> {
    let existing = read_or_nothing(path)?;
    if existing.as_deref() == Some(bytes) {
        return Ok(Written::Unchanged);
    }
    if existing.is_none() {
        create_parent(path)?;
    }
    write(path, bytes)?;
    Ok(if existing.is_some() {
        Written::Updated
    } else {
        Written::Created
    })
}

fn read_or_nothing(path: &Path) -> Result<Option<Vec<u8>>, InstallError> {
    match std::fs::read(path) {
        Ok(bytes) => Ok(Some(bytes)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(InstallError(format!("{}: {e}", path.display()))),
    }
}

fn write(path: &Path, bytes: &[u8]) -> Result<(), InstallError> {
    std::fs::write(path, bytes).map_err(|e| InstallError(format!("{}: {e}", path.display())))
}

fn contains_marker(bytes: &[u8]) -> bool {
    std::str::from_utf8(bytes).is_ok_and(|text| text.lines().any(|line| line == OWNED_BY))
}

fn create_parent(path: &Path) -> Result<(), InstallError> {
    let dir = path
        .parent()
        .ok_or_else(|| InstallError(format!("{} has no parent directory", path.display())))?;
    std::fs::create_dir_all(dir).map_err(|e| InstallError(format!("{}: {e}", dir.display())))
}

/// `$XDG_DATA_HOME`, else `$HOME/.local/share` — the spec's two-step, with the same absolute-path
/// rule [`crate::app_dirs`] applies to the other `XDG_*` variables.
fn data_home(home: Option<&Path>) -> Result<PathBuf, InstallError> {
    if let Some(base) = crate::app_dirs::xdg_base("XDG_DATA_HOME") {
        return Ok(base);
    }
    home.map(|home| home.join(".local/share")).ok_or_else(|| {
        InstallError(
            "neither XDG_DATA_HOME nor a home directory is set, so there is nowhere to \
                      write the desktop entry"
                .to_string(),
        )
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn entry_names_the_icon_and_the_uri_slot() {
        let text = render("ZenMan", "Zen-Man", Path::new("/usr/local/bin/zenman"));
        assert!(text.contains("Icon=zenman\n"), "{text}");
        assert!(text.contains("Exec=/usr/local/bin/zenman %u\n"), "{text}");
        assert!(text.contains("MimeType=inode/directory;"), "{text}");
        assert!(text.contains("StartupWMClass=ZenMan"), "{text}");
        assert!(text.starts_with(OWNED_BY), "{text}");
    }

    #[test]
    fn awkward_paths_are_quoted() {
        assert_eq!(quote_token("/home/a/zen-man"), "/home/a/zen-man");
        assert_eq!(quote_token("/home/a b/zen man"), "\"/home/a b/zen man\"");
        // `\"` and `\\` are the two characters the quoting has to carry, so both survive escaping:
        // i.e. a path with a quote and a backslash in it comes back quoted and escaped.
        let awkward = r#"/tmp/a"b\c/zenman"#;
        assert_eq!(quote_token(awkward), "\"/tmp/a\\\"b\\\\c/zenman\"");
    }

    #[test]
    fn a_foreign_entry_is_never_touched() {
        let dir = scratch("foreign");
        let path = dir.join("ZenMan.desktop");
        std::fs::write(&path, "[Desktop Entry]\nName=Whatever\n").expect("fixture");
        let outcome = write_owned(&path, b"[Desktop Entry]\nName=Zen-Man\n").expect("readable");
        assert!(matches!(outcome, Written::Foreign), "{outcome:?}");
        assert_eq!(
            std::fs::read_to_string(&path).expect("still there"),
            "[Desktop Entry]\nName=Whatever\n"
        );
        // Ours, on the other hand, is updated in place — and what makes it *ours* is the marker,
        // which is why the text `render` writes carries it. A second run has nothing left to do.
        let ours = render("ZenMan", "Zen-Man", Path::new("/tmp/zenman"));
        std::fs::write(&path, format!("{OWNED_BY}\nName=Stale\n")).expect("fixture");
        assert!(
            matches!(
                write_owned(&path, ours.as_bytes()).expect("readable"),
                Written::Updated
            ),
            "an owned entry must follow the binary"
        );
        assert!(
            matches!(
                write_owned(&path, ours.as_bytes()).expect("readable"),
                Written::Unchanged
            ),
            "a second run rewrites nothing"
        );
        remove_tree(&dir);
    }

    #[test]
    fn icon_files_are_written_and_idempotent() {
        let dir = scratch("hicolor");
        let path = dir.join("48x48/apps/zenman.png");
        assert!(matches!(
            write_exact(&path, b"png").expect("writable"),
            Written::Created
        ));
        assert!(matches!(
            write_exact(&path, b"png").expect("writable"),
            Written::Unchanged
        ));
        assert!(matches!(
            write_exact(&path, b"other png").expect("writable"),
            Written::Updated
        ));
        remove_tree(&dir);
    }

    /// Test-only recursive delete. `std::fs::remove_dir_all` is banned workspace-wide (`clippy.toml`,
    /// deletion is a `trash` operation in the product), and the ban does not lift for tests — same
    /// helper, same reason, as `app_dirs`' test module.
    fn remove_tree(path: &Path) {
        let Ok(read) = std::fs::read_dir(path) else {
            return;
        };
        for entry in read.flatten() {
            let child = entry.path();
            if child.is_dir() {
                remove_tree(&child);
            } else {
                let _ = std::fs::remove_file(&child);
            }
        }
        let _ = std::fs::remove_dir(path);
    }

    fn scratch(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("zenman-desktop-{tag}-{}", std::process::id()));
        std::fs::create_dir_all(&dir).expect("scratch directory");
        dir
    }
}
